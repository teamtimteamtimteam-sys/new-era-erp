// lib/sortCollation.ts — 排序用哪一套字序。**一条有名字的规矩,不是一个工具函数。**
//
// ════════════════════════════════════════════════════════════════════════════
// ★★【规矩本身:排序【永远】用英文字序,与界面语言无关】★★
// ════════════════════════════════════════════════════════════════════════════
// Tim 的裁定(COPY-1-SORT-COLLATION):**不论界面是中文还是英文,排序都用英文字序。**
//
// 【为什么是这一条,而不是"跟着界面语言走"】
//   这是一套**多人共用**的系统。六个人隔着桌子互相说「第三行」「某某上面那个」;
//   而一份导出的文件必须与**发信人屏幕上看到的顺序**一致 —— 否则收件人按行号
//   回话时,两个人说的根本不是同一行。**一致性压过舒适度**,这是裁定的全部理由。
//
// 【它的代价,Tim 已经接受,写在这里免得被当成缺陷"修"掉】
//   中文名字会按字符编码排 —— 那既不是拼音序,也不是笔画序,对中文读者不说明任何事。
//   **这是已知代价,不是漏洞。** 要按拼音排,需要的是一个【录入的】拼音排序键
//   (队列里那一条,它要一次迁移;多音字算不出来,所以它不是自动生成的)。
//
// ════════════════════════════════════════════════════════════════════════════
// ★★【为什么写成一个具名标识符,而不是一句"跟着英文界面走"】★★
// ════════════════════════════════════════════════════════════════════════════
// 后者会在将来某一次改【英文界面行为】的刀里**被顺手一起改掉** —— 而这条规矩
// 与界面语言这件事**没有关系**。它有自己的理由(上面那一条),所以它要有自己的名字。
// ☞ **改英文界面的那一刀:这里不归你。** 要动它,先推翻上面那条裁定。
//
// ════════════════════════════════════════════════════════════════════════════
// ★★【不给 locale ≠ 英文。不给 locale = 【运行时默认】,而它会跟着部署环境变。】★★
// ════════════════════════════════════════════════════════════════════════════
// `a.localeCompare(b)` 不带第二个参数时,用的是**运行时自己的默认区域**。
// 实测(2026-09-09,本机):`Intl.Collator().resolvedOptions().locale` = `en-SG`,
// 它排出来的顺序与 `en-US` 逐字相同 —— **所以那些不给 locale 的站点今天是对的,
// 而它们是【碰巧】对的。** 换一个默认区域是中文的运行环境,同一行代码就换了字序,
// 而没有任何东西会说话。
// ☞ 所以排人读的名字的站点**必须显式取字序**,不能靠默认。这是它们改指本模块的理由。
//
// ════════════════════════════════════════════════════════════════════════════
// 【本刀钉的是一条【已经成立】的规矩,不是在修一个正在错的系统】
//   实测(SMALL-BATCH-1 停止闸):真正在排序的那一层是**数据库** ——
//   `app/` + `lib/` 共 413 处 `.order()`,`db/` 共 864 处 `ORDER BY`,
//   而线上库的字序是 `en_US.UTF-8`,`db/` 里没有任何列级 `COLLATE`。
//   实测同一组样本:Postgres 与 Node 的英文序**逐字吻合**
//   (`Alpha | beta | 张三 | 李四 | 陈一`),而 `zh-Hans-CN` 是完全另一个顺序
//   (`陈一 | 李四 | 张三 | Alpha | beta`)。
//   ☞ **也就是说这条裁定在真正排序的那一层今天就已经生效了。**
//     本模块做的是把它**写下来**,并关掉两个反例(见下)。
// ════════════════════════════════════════════════════════════════════════════

/**
 * ★ 排序字序的**唯一出处**。改这一行等于推翻上面那条裁定 —— 不要顺手改。
 *
 * 用 `'en'`(不带地区)而不是 `'en-SG'` / `'en-US'`:地区只影响日期与数字的**格式**,
 * 不影响字序,而写死一个地区会让人以为那个地区是有意义的。
 */
export const SORT_COLLATION = 'en'

/**
 * 按本仓库的排序规矩比较两个字符串。
 *
 * @param options 原样透传给 `localeCompare` 的第三个参数。
 *   ★ **刻意不给默认值**:本刀把六处站点改指这里,而它们各自现有的
 *   `numeric` 行为必须【一字不变】—— 表格那一处本来就带 `{ numeric: true }`,
 *   其余五处本来就没有。悄悄给所有人加上 `numeric` 会让 "item2 / item10"
 *   的顺序在五张屏幕上一起变,**而这一刀的走查说不清那是字序改的还是数字序改的。**
 *   这一刀只改字序,别的一样都不改。
 */
export function compareForSort(
    a: string,
    b: string,
    options?: Intl.CollatorOptions,
): number {
    return a.localeCompare(b, SORT_COLLATION, options)
}
