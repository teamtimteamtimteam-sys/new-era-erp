// lib/session.ts
// 【会话空闲超时的唯一一个家】—— 这个文件就是 3.4 说的那个"可见的配置"。
//
// ════════════════════════════════════════════════════════════════════════════
// 为什么是【一个常量文件】而不是一张配置表(IDLE-DRAFT,2026-08-24)
//
// 这不是一个 per-install 的值,它是 Tim 在 2026-08-23 为这家公司裁定的一条政策:
// 三十分钟。放进数据库需要一张设置屏、一条写入判据、一次迁移,以及"谁能改它"
// 这个问题的答案 —— 而那正是 APPROVALS-SWITCH-UNGUARDED 今天还开着的那一半。
// 为一个不会按部署变化的值造出那一整套,是拿复杂度换一个不存在的区别。
//
// 【还有一条更硬的理由:中间件读不起数据库。】这两个数字【必须】同时被
// 中间件(每一个请求都跑)与浏览器读到。放在库里就意味着每一个请求一次查询,
// 或者一层缓存 —— 而缓存的失效又是一个新问题。放在这里,两边 import 同一个常量,
// 不存在"两处配置漂开"这种事。
//
// 【要改成 per-install 的那一天,判据是什么】某个装机点需要一个不同的分钟数,
// 并且那个需求是真的(不是"也许有人会想要")。那时它才值一张表。
// ════════════════════════════════════════════════════════════════════════════

/** 空闲多久算超时。Tim 2026-08-23 裁定:30 分钟。 */
export const IDLE_TIMEOUT_MS = 30 * 60 * 1000

/**
 * 提前多久预警。裁定:两分钟。
 *
 * **这个预警不是装饰,它是三十分钟【可以被接受】的全部理由。** 没有它,
 * 一次超时就是一次没有预告的工作损失,只是多了几步。
 */
export const IDLE_WARNING_MS = 2 * 60 * 1000

/**
 * 记录"最后一次真实活动"的 cookie 名。
 *
 * 【它只由浏览器写,中间件【永远】不写 —— 这一句是整件事的承重墙】
 * 见 lib/supabase/middleware.ts 里同一条注释。中间件一旦顺手刷新它,
 * 每一次 RSC 预取都会算作活动,超时就永远不会触发。
 */
export const ACTIVITY_COOKIE = 'evoltrya-last-activity'

/**
 * 浏览器最多多久写一次这个 cookie。
 * 每一次按键都写一次 cookie 是没有意义的开销;30 秒的粒度对一个 30 分钟的
 * 窗口毫无影响(最坏情况把超时推后 30 秒)。
 */
export const ACTIVITY_WRITE_THROTTLE_MS = 30 * 1000

/**
 * 草稿的保存期限:**72 小时**。
 *
 * 【为什么是 72 而不是 24 或 168】要覆盖的最长一次【合理】的中断是一个周末 ——
 * 周五傍晚起了个头,周一早上回来接着做。24 小时会在周一早上悄悄把周五的草稿丢掉,
 * 而那正是人最指望它还在的时刻。168 小时(一周)覆盖得更多,代价是一份没人再要的
 * 草稿在浏览器里躺满一整周 —— 而这些设备是车间里共用的。
 * **72 小时是覆盖住周末这一情形的最小窗口。**
 */
export const DRAFT_MAX_AGE_MS = 72 * 60 * 60 * 1000

/** 判断一个活动时间戳是否已经过期(空缺 = 不过期,见中间件里的理由)。 */
export function isIdleExpired(lastActivityMs: number | null, now = Date.now()): boolean {
    if (lastActivityMs === null || !Number.isFinite(lastActivityMs)) return false
    return now - lastActivityMs >= IDLE_TIMEOUT_MS
}
