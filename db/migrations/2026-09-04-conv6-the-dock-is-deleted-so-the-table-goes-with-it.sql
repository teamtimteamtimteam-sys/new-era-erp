-- 【裁定】Tim,2026-09-04:二级菜单已经足够直接、模块划分足够清楚,dock 只是把
-- 界面弄复杂、还吃掉屏幕面积。**这一条推翻 D1 的后半**(「结构是共享且固定的,
-- dock 是个人的」),也**取代 UI-FIX-1 把它挪成左侧竖栏**那一次补救 ——
-- 那一次答的是"它读起来像第三层菜单",这一次答的是它该不该存在。
--
-- 【为什么表也要删,而不是留着"以后可能还要"】
--   这张表存的是 dock 的内容与收起状态。UI 没了,它就没有任何写者、没有任何读者。
--   一张没有读者的表在下一个人眼里是【这个功能还在,只是我没找到入口】——
--   与 CONV-6 ① 删掉 check:dock 是同一条理由:一条守着不存在之物的检查,
--   比没有检查更坏。数据本身:**一行,Tim 自己那一行**(迁移前实测 count = 1,
--   user_id 321f1819…,七条 hrefs,collapsed = true)。
--
-- 【DROP TABLE 连带删掉的东西,写出来免得下一个人以为它们还在】
--   · 四条 RLS 策略(select/insert/update/delete own,实测 pg_policies 4 行);
--   · PRIMARY KEY 与那条指向 auth.users 的 FK;
--   · 两条列注释与一条表注释。
--   没有触发器、没有视图、没有函数读它 —— 全库查过,引用它的只有已删的
--   app/components/nav/dockActions.ts 一处。
--
-- ★★【顺序:这一支【在部署之后】才应用,而那是【刻意反过来】的】★★
--   AGENTS.md 的常规是"备份 → 迁移 → 推送 → 部署",而那条顺序假设的是
--   【迁移不会打断旧代码】(加一列、放宽一条策略)。**这一支不是那一种**:
--   它删掉的是一张【旧代码每一页都读】的表 —— DockRail 长在根布局上,
--   readDock() 查不到表就抛,于是在"迁移已提交、部署还没落地"那段窗口里,
--   生产对每一个登录用户【每一页都是 500】。那不是一处降级,是一次全站中断。
--   所以本刀把顺序倒过来:**先让不读这张表的新代码上线,再删表。**
--   窗口里生产跑的是【新代码 + 旧库】—— 新代码一个字都不提 user_dock,
--   所以那段时间【什么都不坏】。破窗时长照报,见本刀报告。
--
-- 【备份】迁移前在前台跑完,脚本自报 BACKUP_EXIT=0(2026-09-04 07:56 起,
--   evoltrya-backup-2026-09-04-0756.dump,4.0M,TOC 5282 条 / 上一份 5272 条)。
--   ★ 备份【跑完】才动库(SO-3b:pg_dump 持 ACCESS SHARE,与 DDL 要的
--     ACCESS EXCLUSIVE 冲突,"起过就动"会让迁移卡在等锁上直到语句超时)。
-- ════════════════════════════════════════════════════════════════════════════

BEGIN;

