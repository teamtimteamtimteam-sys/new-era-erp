-- IOD-1 续:allowed_classes 的表注释改指 IOD-2 —— 原来那句在本刀合并的瞬间变成假的
--
-- LOC-1 写的是"落闸的地方是出入库单据那一刀"。那一刀就是 IOD-1,而 IOD-1
-- **落完了、并没有设闸**。于是那句注释指着一个已经过去的时点 —— 与
-- AGENTS.md 里那条"一句描述已不存在的危险的注释,和一句断言不可能发生的
-- 危险的注释,是同一种缺陷"完全同形:它不会让任何门变红,只会让读的人
-- 相信一件不成立的事。
--
-- 顺带把 IOD-1 的 survey 撞到的第三态写进注释:未分类物料落在已配置库位上,
-- 天真的谓词会让它掉进"拒绝",而未分类不是被排除,是没人分过类。
--
-- 镜像:db/tables/storage_location_allowed_classes.sql(表头亦已改)。

BEGIN;

COMMENT ON TABLE public.storage_location_allowed_classes IS
    'LOC-1:库位可存放的受控物料分类。一行 = 这个库位可以放这一类。【零行 = 未配置 = 还没决定】,将来的检查对它告警而绝不拒绝 —— 与"配了、但不含这一类"(有人做过决定,该拒)是两回事,压成一个布尔量就是把"没人想过"演成"想过、结论是不行"。【本表只记录,不设闸】:IOD-1(出入库单据那一刀)已经落完,并没有设闸 —— 落闸归 IOD-2。今天没有任何东西因为这张表拒绝过一次收货或移库。IOD-2 还要一并决定【未分类物料】落在已配置库位上算什么:天真的谓词会让它掉进拒绝,而未分类不是被排除,是没人分过类。';

COMMIT;
