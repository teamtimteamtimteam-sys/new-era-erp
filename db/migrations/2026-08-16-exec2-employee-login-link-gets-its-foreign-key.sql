-- EXEC-2:员工↔登录账号那根线终于有了外键
--
-- ═══════════════════════════════════════════════════════════════════════════
-- `employees.user_id` 从建表那天起就没有指向 auth.users 的外键 —— 这件事在
-- docs/known-issues.md 里躺了十二天(2026-08-04 记)。它的代价很具体:
-- **敲错一个 uuid 会静默入库**,而这一列的读者是"这份签发档是谁签的"
-- (INV-2b 的签发人列)与绩效评估的分派路径 —— 两处都不会报错,只会
-- 【查不到人】,而"查不到人"与"这个人没有账号"在屏幕上长得一模一样。
--
-- 【为什么现在补,而不是等 org-fill 那一刀】EXEC-0b 的计划里写着组织图填充要
-- "所有员工录入、user_id 只连有登录账号的人、同一刀补上这个外键"。
-- **而三件事里只有这一件必须【在敲之前】做完** —— 那一刀正是要大批量地敲这一列,
-- 补在后面等于先造一批可能错的行、再去验它们。所以它提前单独走一刀。
--
-- 【ON DELETE SET NULL,不是 CASCADE、也不是 RESTRICT】三种都想过:
--   * CASCADE 会因为删掉一个登录账号而【删掉那个员工】—— 员工档案是 HR 的记录,
--     它的存在与这个人有没有系统账号毫无关系;
--   * RESTRICT 会让"回收一个离职者的登录账号"这件正当的事被一条外键拦住,
--     而拦住之后人会去手工把 user_id 清成 NULL —— 那正是这条外键想要的结果,
--     只是绕了一圈、还多了一次手工操作;
--   * SET NULL 说的正是真话:**账号没了,人还在,那根线断了**。
--
-- 【前置检查已经跑过,结果写在这里】线上非空的 user_id 只有一行,而它解析得出来
-- (孤儿 0)。有意思的是那一行是 `ZZ-SMOKE-2` —— 冒烟脚本被 kill 之后留下的临时行。
-- 也就是说【今天唯一在用这一列的,是一行残骸】,而真实的组织图还没有录进来。
-- 这对本刀是好消息:约束加在一列几乎没有真数据的列上,风险最小。
-- ═══════════════════════════════════════════════════════════════════════════

BEGIN;

ALTER TABLE public.employees
    ADD CONSTRAINT employees_user_id_fkey
    FOREIGN KEY (user_id) REFERENCES auth.users (id) ON DELETE SET NULL;

COMMENT ON COLUMN public.employees.user_id IS
    '这名员工的登录账号(auth.users.id)。EXEC-2 起有外键:敲错一个 uuid 会当场被拒,而不是静默入库 —— 这一列的读者(签发人姓名、绩效评估的分派路径)遇到一个指向空气的 id 时只会【查不到人】,而"查不到人"与"这个人没有账号"在屏幕上一模一样。ON DELETE SET NULL:账号被回收时,员工档案原样留着,只是那根线断了 —— 员工是 HR 的记录,它的存在与这个人有没有系统账号无关。可空是常态:不是每个员工都需要账号。';

COMMIT;
