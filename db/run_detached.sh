#!/bin/bash
# db/run_detached.sh —— 后台跑一支长脚本,而【判词只能来自脚本自己打出来的那一行】。
#
# ════════════════════════════════════════════════════════════════════════════
# 【为什么存在:同一个形状在一次会话里骗了五次】(EQP-2c,2026-08-21)
#
# AGENTS.md 已经把判据写清楚了 ——
#
#   > 备份跑完的唯一证据,是 backup.log 里那一行【脚本自己打出来的退出码】。
#   > 不是启动器的状态、不是通知、不是 pgrep、不是文件存在、不是 ls -t 最新的那个。
#
# 那句话是对的,而且写在正确的地方。**它没能拦住任何一次。** 同一次会话里
# 【启动器的退出码冒充了脚本的退出码】五次:备份一次,冒烟四次。每一次的画面
# 都一样 —— harness 报「completed (exit code 0)」,而脚本还在跑,日志里连总结行
# 都没有。EQP-1c-b-fu2 的提交信息把第四次记了下来,然后第五次照样发生。
#
# **一条要靠人记着的规矩,已经证明了它记不住。** 这个仓库对这件事有一条成文的
# 处置(OPS-7 用脚本替掉两句"记得检查 B1 与 is_system";db/wait_for.sh 替掉
# "记得给等待加上限"):**把注解换成机制。** 这支脚本就是那次替换。
#
# 【它做的三件事,每一件对着上面那句话的一半】
#   ① 把命令跑在一个子壳里,并让【那个子壳】把命令自己的退出码追加成
#      `<TOKEN>_EXIT=<n>` —— 于是日志里那一行的作者是被等的那支脚本,
#      不是启动它的东西;
#   ② 用 db/wait_for.sh 等那一行出现(有上限、有失败分支,不自己手写 until 循环);
#   ③ **拿不到那一行就【拒绝给判词】** —— 退出码 3,并明说"没有拿到脚本自己的
#      退出码,所以本脚本【不知道】它成没成功"。这一条是重点:一个说不出话的
#      检查必须说"我不知道",绝不能沉默着变绿。
#
# 【为什么是包装,而不是"以后都记得写那三行"】那三行(子壳 + wait_for + grep)
# 正是 AGENTS.md 已经写出来的样板,而它被跳过了五次。样板与机制的区别就是这个:
# 样板要人照抄,机制不照抄就跑不起来。
#
# 【它不解决什么,写下来免得被当成万能】它证明的只是"那支脚本跑完了,退出码是 n"。
# 脚本自己撒谎(BK-FIX 之前的 backup.sh:印着失败却退 0)不在它的射程内 ——
# 那一条的处置是修那支脚本,已经做过了。两条判据叠在一起才完整:
# **脚本要说真话(BK-FIX),而它说的话要真的被读到(本脚本)。**
#
# ════════════════════════════════════════════════════════════════════════════
# ★★【OPS-TIMEOUT(2026-08-29):到点杀的是【进程组】,而且【先写判词再动手】】★★
#
# 【它修的那个缺陷,以及它为什么排在功能前面】
#   这支脚本本身是"把注解换成机制"的产物,而**它自己长出了同一个病,并且犯了两次
#   ——一天之内**:GST-1 撞在路由冒烟上(2026-08-24),GST-2 撞在 check_mirrors 上
#   (2026-08-25)。两次都是【活干完了,判词一行都没有】,两次都是人眼发现的。
#   本仓库自己的门槛就是这个:同一个形状撞第二次,不再写注解,改成机制。
#
# 【旧行为,2026-08-29 逐条复现过,不是从记录里抄的】
#   `( "$@" …; echo "${MARK}$?" ) &` 里 `$!` 拿到的是【子壳】的 pid,
#   而 `"$@"` 是子壳的【孙子】。于是 `kill "$CHILD"`:
#     · 子壳死(实测 pid 74786,`Terminated: 15`);
#     · **真正干活的那支活下来,ppid 变成 1**(实测 74788,连同它的 `sleep 300`);
#     · 而**被杀掉的子壳,正是将来要写 `${MARK}$?` 那一行的人** ——
#       于是那一行**不是"还没打",是"再也不会打"**。
#   坏处不在于多了一个孤儿,在于**沉默与成功长得一模一样**:
#   一个绕过上限的等待器会对着一件【哪儿都不存在】的事空转下去(实测代价:87 分钟)。
#
# 【现在的行为,两件事,而第二件更要紧】
#   ① **`set -m` 让子壳自成一个进程组**,到点按【组】发信号,于是孙子跟着走,
#      没有东西认得了 init 当父亲。(macOS 没有 setsid(1);bash 3.2 下
#      `set -m` 实测有效:子壳 pid == 它自己的 pgid,孙子同组,
#      而 run_detached 自己在另一个组里,按组杀不会杀到自己。)
#   ② ★**在杀之前,先把 `${MARK}124` 写进日志**★ —— 让"被超时终止"成为一个
#      **有作者的判词**,而不是一片沉默。**今天的缺陷不是"活没死",是"没人说过话"。**
#
# 【为什么是 124,而不是 137/143】
#   `128+信号` 那两个数**已经有别的含义了**:`docs/concurrency-one-tree-one-smoke.md`
#   记着一次 `SMOKE_EXIT=137`,意思是"撞了端口、被 SIGKILL 打死"。
#   复用它,就让「我的监督者把我超时了」与「别的什么东西把我杀了」**读起来一模一样**
#   —— 而那正是这一刀要消灭的那种含混。124 是 `timeout(1)` 的「命令超时」,
#   与 `128+n` 不撞,与本脚本自己的 2(用法错)/ 3(判词未知)也不撞。
#
# 【到点之后本脚本退 124,不再退 3 —— 因为它不再是"不知道"】
#   而且那个 124 是**从日志里那一行读出来的**,不是另外写一遍:超时之后代码
#   **落到与正常收尾完全同一段读取/报告的路上**。于是只有一个读者、一份真源,
#   退出码与日志【不可能各说各话】。
#   **3 只留给真正拿不到那一行的情形**(日志写不进去之类)——
#   一个说不出话的检查必须说"我不知道",而不能沉默着变绿。
#
# 【残留的那个窗口,量过,不含糊过去】
#   到点这一刻,活可能【刚好】干完。所以写 124 之前先 `grep` 一眼:已经有真判词
#   就不写。这仍然是一次 check-then-act,窗口是那次 grep 到那次 append 之间 ——
#   **量过,不是"一个很小的窗口":2026-08-29 采样 200 次(grep 未命中、扫全文件,
#   再 append 一行),中位数 1.67 ms · p95 1.95 ms · 最大 2.53 ms。**
#   也就是说:一支活要落进这个窗口,得【恰好】在上限到点之后的那 2 毫秒里干完。
#   落进去的会被记成超时,而它其实成了 —— 这是这个取舍的全部代价。
#   **没有把窗口做到零,是一个刻意的取舍**:做到零要让【读者】变聪明
#   (在两行里挑),而读者正是每一个调用点都要手抄的那一半 ——
#   一个更窄的竞态配一句诚实的话,胜过一个没人抄得对的更大的修法。
#
# 【Ctrl-C:这一刀差点用一个孤儿换来另一个孤儿】
#   进程组一分开,**终端的 SIGINT 就不再传到那支活身上了** ——
#   在此之前它们同组,Ctrl-C 是到得了的。所以本脚本自己 trap INT/TERM
#   并**转发给那个组**。见下面那段 trap:**下一个来"简化"这里的人看不到这句话,
#   就会把它删掉,然后在键盘上造出这一刀刚刚在上限处消灭掉的那个孤儿。**
# ════════════════════════════════════════════════════════════════════════════
#
# 用法:
#     db/run_detached.sh --log /tmp/backup.log --label "备份" --timeout 2400 \
#         -- ~/evoltrya-backups/backup.sh
#
# ★【--timeout 从一次【实测的成本】推出来,加余量 —— 不是挑一个看起来够大的整数】★
#   **这条规矩带着它自己的事故,因为一条光秃秃的规矩会被下一个人编辑掉:**
#   上面说的第二次(GST-2,2026-08-25)的直接起因**不是**子壳,是
#   `--timeout 900` 被安在一支**实测约十五分钟**的活上 —— 上限与成本一样长、
#   **零余量**。于是 check_mirrors 在干完前【一分钟】被砍,
#   而它本来会成功。**那次上限把"还在跑"翻译成了一次误杀。**
#   两个方向都会错:太小 → 误杀,而误杀留下的日志和真失败长得一模一样;
#   太大 → 一支真卡死的活要等到那个数才有人知道。
#   本仓库对成本已经有一条规矩(写下来的成本必须是量过的成本);
#   **这一句是它的另一半:量过的成本,还要真的被用进上限里。**
#
# 退出码:被等脚本自己的退出码 · 124 = 到点被本脚本终止(判词【已授权】)
#         · 3 = 拿不到那一行(判词【未知】) · 2 = 用法错误
#         · 130/143 = 本脚本自己被 Ctrl-C / SIGTERM,已把信号转发给那个组
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LOG=""; LABEL=""; TIMEOUT=""; TOKEN="RUN"; INTERVAL=10
while [ $# -gt 0 ]; do
    case "$1" in
        --log)      LOG="${2:-}";      shift 2 ;;
        --label)    LABEL="${2:-}";    shift 2 ;;
        --timeout)  TIMEOUT="${2:-}";  shift 2 ;;
        --token)    TOKEN="${2:-}";    shift 2 ;;
        --interval) INTERVAL="${2:-}"; shift 2 ;;
        --) shift; break ;;
        *) echo "✗ run_detached:认不得的参数 $1" >&2; exit 2 ;;
    esac
done
# 【三个都必填,一个默认值都不给】理由与 wait_for.sh 逐字相同:给了默认值,
# 上限就又变成了"可以不想",而不想正是这支脚本要消灭的东西。
[ -n "$LOG" ]     || { echo "✗ run_detached:必须给 --log <日志路径>" >&2; exit 2; }
[ -n "$LABEL" ]   || { echo "✗ run_detached:必须给 --label <等的是什么>" >&2; exit 2; }
[ -n "$TIMEOUT" ] || { echo "✗ run_detached:必须给 --timeout <秒>" >&2; exit 2; }
[ $# -gt 0 ]      || { echo "✗ run_detached:-- 之后要给一条命令" >&2; exit 2; }
case "$TIMEOUT" in ''|*[!0-9]*) echo "✗ run_detached:--timeout 必须是整数秒" >&2; exit 2 ;; esac
case "$TOKEN" in ''|*[!A-Z0-9_]*) echo "✗ run_detached:--token 只能是大写字母数字下划线" >&2; exit 2 ;; esac

MARK="${TOKEN}_EXIT="
# 【到点那个判词的值】124 = timeout(1) 的「命令超时」。为什么不是 137/143,
# 见抬头 —— 那两个数在本仓库已经有别的含义了。
TIMEOUT_VERDICT=124
# 【宽限期:先礼后兵之间等多久 —— 这个数是【量出来的】,不是挑的】
#   2026-08-29 实测(结构与下面完全一致:set -m → 子壳自成一组 → 按组发 TERM,
#   量的是"发信号 → 整组消失"):
#       bash(sleep)            0.021s
#       node                    0.124s   ← 最慢的一个
#       python3 + 库连接(事务中) 0.017s
#       psql(事务中)           0.020s
#   最慢 0.124s,取 5s ≈ 它的 40 倍。**余量给的是这台机器自己的抖动**:
#   同一支 gate 在同一天量到过 130s 与 483s(3.7 倍),隧道 select 1 量到过
#   2.9s 与 7.6s —— 一台会这样抖的机器,不该用一个贴着实测值的宽限期,
#   否则退化的那一天会把"正在干净退出"打成 SIGKILL。
#   5s 也短到不会把一支真卡死的活拖成一次漫长的等待。
GRACE=5
: > "$LOG"
echo "▶ $LABEL —— 后台起,判词只认日志里那一行 ^${MARK}" >&2

# ① 子壳里跑,子壳负责把【命令自己的】退出码追加进日志。
#    这里刻意不用 `cmd &` 再读 $? —— 那读到的是启动它的那一层。
#
#    ★【set -m 是为了让子壳【自成一个进程组】】★ 非交互的脚本里 job control 默认
#      是关的,于是 `( … ) &` 会留在 **run_detached 自己的**进程组里 ——
#      那样按组杀会把 run_detached 连同它自己一起杀掉。开了 monitor 模式之后,
#      子壳的 pgid == 它自己的 pid,孙子进程跟着进同一组,于是到点按 `-$CHILD`
#      发信号,收的是【那支活和它所有的后代】,收不到本脚本。
#      (macOS 没有 setsid(1);bash 3.2 下这条实测有效。)
set -m
( "$@" >>"$LOG" 2>&1; echo "${MARK}$?" >>"$LOG" ) &
CHILD=$!
set +m

# ★★【trap:进程组一分开,Ctrl-C 就不再到得了那支活 —— 所以自己转发】★★
#   **这三行是这一刀差点犯下的那个错的补丁,不是装饰。**
#   在 set -m 之前,run_detached 与那支活【同组】,终端的 SIGINT 一发全收;
#   分了组之后,Ctrl-C 只打到本脚本身上,那支活会活下来、认 init 当父亲 ——
#   **也就是说,这一刀会在上限处消灭一个孤儿,同时在键盘上造出另一个。**
#   下一个来"简化"这里的人看不到这句话就会把它删掉,所以它写在这里,不写在别处。
#   ★【而 trap 要真的跑得起来,等待就【不能】是一个前台子进程】★
#     实测(2026-08-29):bash 在等一个【前台】子进程时,会把 trap **推迟到那个
#     子进程结束之后** —— 于是信号来了,run_detached 一声不吭地继续等,
#     而那支活也没收到转发。**一个装了却跑不起来的 trap,比没装更坏:
#     它看起来已经把这件事处理掉了。**
#     所以下面把 wait_for.sh 放到【后台】再 `wait` 它 —— 同一次实测里,
#     后台 + wait 的那一支 trap 立刻就跑了。
#   (顺带一条踩过的坑,免得下一个人像我一样测错:用 `cmd &` 从一个非交互 shell
#    起进程时,SIGINT/SIGQUIT 在子进程里是【入口即被忽略】的,而入口被忽略的信号
#    `trap` 装不上。所以这条 trap 测不了 SIGINT,只能拿 SIGTERM 测 ——
#    真实的 Ctrl-C 走的是前台进程组,不受那条规则约束。)
cleanup_and_exit() {   # $1 = 信号名 · $2 = 退出码
    echo "⚠ $LABEL:收到 $1,已把它转发给那支活的进程组($CHILD)" >&2
    kill -TERM -- "-$CHILD" 2>/dev/null
    [ -n "${WPID:-}" ] && kill -TERM "$WPID" 2>/dev/null
    exit "$2"
}
trap 'cleanup_and_exit SIGINT 130' INT
trap 'cleanup_and_exit SIGTERM 143' TERM

# ② 等那一行出现。条件放在 sh -c 里【每一轮重新求值】—— 命令替换会在
#    wait_for 起跑之前就被外层壳算完一次,把条件冻死(AGENTS.md 记过一次 877 秒)。
#    ★ 放【后台】再 wait,理由见上面那段 trap:前台子进程会把 trap 推迟掉。
"$HERE/wait_for.sh" --timeout "$TIMEOUT" --interval "$INTERVAL" \
    --label "$LABEL:脚本自报退出码(^${MARK})" \
    -- sh -c "grep -q '^${MARK}' '$LOG'" &
WPID=$!
wait "$WPID"
WAITED=$?

# ③ 到点了。★【顺序就是这一刀的全部要点:先写判词,再动手杀】★
#    判词写在杀之前,是因为**写在杀之后会被竞态吃掉** —— 而那正是旧行为的病:
#    杀掉的那个子壳就是判词的作者,于是判词永远不会出现。
#    这里由【语句顺序】保证:`echo >>` 是一条完整语句,它返回时 write(2) 已经回来了,
#    下一条 `kill` 才开始。而 `>>` 走 O_APPEND、那一行不到 20 字节(远小于 PIPE_BUF),
#    所以即便那支活同时还在往同一个日志里写,这一行也不会被撕开。
if [ "$WAITED" -ne 0 ]; then
    # (i) 【到点这一刻,活可能刚好干完】先看一眼:已经有真判词就不写我的。
    #     残留的窗口是这次 grep 到下面那次 append 之间(实测量级见抬头),
    #     **没有做到零是一个刻意的取舍,理由写在抬头。**
    if grep -q "^${MARK}" "$LOG" 2>/dev/null; then
        echo "ℹ $LABEL:到点的同一刻那支活自己写出了判词 —— 用它的,不用超时的。" >&2
    else
        echo "${MARK}${TIMEOUT_VERDICT}" >>"$LOG"
        echo "✗ $LABEL:${TIMEOUT}s 到点,本脚本写下 ${MARK}${TIMEOUT_VERDICT}(= 被超时终止)并开始收尾。" >&2
        echo "  **这不是那支活自己说的话,是【本脚本授权的一句判词】** —— " >&2
        echo "  在此之前,这里是一片沉默,而沉默与成功长得一模一样。" >&2
    fi

    # (ii) 判词落盘了,现在才动手。**先礼**:给整个进程组发 TERM。
    kill -TERM -- "-$CHILD" 2>/dev/null
    WAITED_OUT=0
    while kill -0 -- "-$CHILD" 2>/dev/null; do
        if [ "$WAITED_OUT" -ge "$GRACE" ]; then break; fi
        sleep 1
        WAITED_OUT=$(( WAITED_OUT + 1 ))
    done

    # (iii) **后兵**:宽限期内没走干净,就按组 SIGKILL。
    #       先礼是为了让那支活有机会自己收尾 —— 尤其是把库连接关掉:
    #       本仓库记着一次 7 分 12 秒的 idle in transaction,来路正是一次粗暴的终止。
    #       (2026-08-29 实测:psql 与 python3 在事务中被 TERM 之后,
    #        服务端那两个 backend 都干净消失了,全局 idle_in_txn = 0 ——
    #        **但那是一次测量,不是一个保证**;真遇上残留,处置仍然是
    #        `pg_terminate_backend`,见 AGENTS.md。)
    if kill -0 -- "-$CHILD" 2>/dev/null; then
        echo "  ⚠ 宽限 ${GRACE}s 之后那个进程组还在 —— 改发 SIGKILL。" >&2
        kill -KILL -- "-$CHILD" 2>/dev/null
        sleep 1
    fi

    # (iv) 【收干净了吗?说出来,不要假定】—— 这一句在的理由与本刀一样:
    #      "我以为它死了"和"它真的死了"必须分得开。
    if kill -0 -- "-$CHILD" 2>/dev/null; then
        echo "  ★ $LABEL:SIGKILL 之后那个进程组【仍然在】—— 这是一个发现,不是一次正常收尾。" >&2
        echo "    自己看一眼:ps -eo pid,ppid,pgid,args | awk '\$3==$CHILD'" >&2
    else
        echo "  ✓ $LABEL:那支活和它的后代都收干净了(进程组 $CHILD 已不存在)。" >&2
    fi
    echo "  日志尾巴($LOG):" >&2
    tail -n 15 "$LOG" >&2
    # (v) ★【不在这里 exit】★ 落到下面那段【与正常收尾完全同一段】的读取/报告里。
    #     于是只有一个读者、一份真源,退出码与日志不可能各说各话。
fi

# ④ 【唯一的读者】正常收尾与超时收尾都落到这里,退出码【从日志里那一行读出来】,
#    不另外写一遍 —— 两个地方各写一次,就是两份真源,而它们迟早会各说各话。
REAL=$(grep -m1 "^${MARK}" "$LOG" | sed "s/^${MARK}//")
case "$REAL" in ''|*[!0-9]*)
    # 【3 只剩这一个含义了】连那一行都拿不到(日志写不进去之类)。
    # 超时不再走这条路 —— 超时现在有判词。
    echo "✗ $LABEL:那一行读出来不是一个数字(「$REAL」)—— 判词【未知】" >&2; exit 3 ;;
esac
if [ "$REAL" -eq 0 ]; then
    echo "✓ $LABEL:脚本自报 ${MARK}0" >&2
elif [ "$REAL" -eq "$TIMEOUT_VERDICT" ] && [ "$WAITED" -ne 0 ]; then
    echo "✗ $LABEL:${MARK}${TIMEOUT_VERDICT} —— 【到点被本脚本终止】,不是那支活自己失败的。" >&2
    echo "  要么它真的卡住了,要么这个上限太小 —— 上限该从一次实测的成本推出来(见抬头)。" >&2
else
    echo "✗ $LABEL:脚本自报 ${MARK}${REAL}" >&2
fi
exit "$REAL"
