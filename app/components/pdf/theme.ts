// app/components/pdf/theme.ts
// PDF-1:对外单据的【一份版式】—— 颜色、尺寸、表格、页脚。(2026-09-02)
//
// ════════════════════════════════════════════════════════════════════════════
// 【这一份东西此前有七份副本】
// ════════════════════════════════════════════════════════════════════════════
// 落地前实测:七份 bespoke 文档各自 StyleSheet.create 了一遍几乎相同的
// page / title / code / metaRow / metaLabel / metaBlock / tableHeader / row /
// cell / footer,数值只差一点点(padding 36 与 40 两种、metaLabel 宽 90/100/110)。
// `tableHeader` 与 `row` 在其中【五份里逐字相同】。
// 三份还各自写了一遍同一个 money():`n.toLocaleString('en-US', {min:2,max:2})`。
//
// 于是"改一下表格的分隔线颜色"是一件要动七个文件的事,而且没有任何东西会提醒
// 漏了哪一个 —— 这正是 `docs/known-issues.md`(EQP-1c-b-fu2)对公司抬头写下的
// 那句预言,在版式上的同一次兑现。
//
// ════════════════════════════════════════════════════════════════════════════
// 【为什么是"一组零件",不是一个 <DocumentShell> 包住一切】
// ════════════════════════════════════════════════════════════════════════════
// 八份单据的骨架真的不一样:发票有付款账户块与作废水印,采购单有付款里程碑与
// 承诺定价条款,送货单有受控废物分类栏,对账单是结转式摘要 + 账龄分档。
// 硬压成一个组件,只会得到一个包着八份实现的 switch —— 那正是 CompanyLetterhead
// 抬头写下的那条分寸(抽【内容与规则】,不抽【每一处版式】)。
//
// 所以这里给的是:**一份共享的 StyleSheet + 三个共享组件**(字标抬头、表格头、
// 页脚)。每份单据仍然自己排它自己的骨架,但"一条分隔线多粗、表头什么底色、
// 页码印在哪"从此只有一处。
//
// ════════════════════════════════════════════════════════════════════════════
// 【颜色:R1 的品牌指南,一个字都不自己发挥】
// ════════════════════════════════════════════════════════════════════════════
//   #008EBC Hawaiian Ocean · #6B8D54 Forest Green · #F1F9FE 背景
//   #E1F5FF 强调 · #182B4B 正文
//
// ★【纸不是屏幕 —— 这几条是【印刷】上的取舍,写下来免得被当成随手改的】★
//   * 正文从 #111827(既有文档用的中性近黑)换成 **#182B4B**(品牌正文色)。
//     实测白底 **14.13:1**,远高于正文所需,黑白打印机上也仍然是深色。
//   * **底色只用在表头一行**(#E1F5FF)。整页铺 #F1F9FE 会让每一张单据都吃掉
//     一整页的墨,而客户与审计师【会打印它】—— 纸本身就是白的,背景色在屏幕上
//     是设计,在打印机上是成本。所以页面底色留白。
//   * 分隔线用 Ocean 的淡化版而不是灰:细线在传真与低质黑白打印下容易丢,
//     所以主分隔线保持 **1pt 实色**,次级分隔线才用淡色。
//
// ★★【Ocean 与 Forest 都【不许】用作正文颜色 —— 这是量出来的,不是风格偏好】★★
//   实测白底对比度:**Ocean #008EBC 3.75:1 · Forest #6B8D54 3.77:1**,
//   而 WCAG 正文要 4.5:1。两个品牌主色【都不够】。
//   它们只可以用在:分隔线与边框、以及【大号】标题(≥18pt 粗体,门槛 3:1)。
//   下一个想把正文或小字标签染成品牌蓝的人:**先算,再写** —— 一张对账单上的
//   小字如果只有 3.75:1,打印出来最先看不清的就是它。
//   正文一律 BRAND.text(14.13:1),次级一律 BRAND.muted(5.42:1)。
export const BRAND = {
    ocean: '#008EBC',
    forest: '#6B8D54',
    bg: '#F1F9FE',
    accent: '#E1F5FF',
    text: '#182B4B',
    /** 次级文字(标签、页脚)—— 正文色的淡化版。白底实测 5.42:1、表头底色上 4.83:1,
     *  两处都过 AA 正文所需的 4.5:1(算到小数,不靠眼估)。 */
    muted: '#5A6B85',
    /** 次级分隔线。只用于行与行之间,主分隔线一律用 text 或 ocean。 */
    hairline: '#CFE6F2',
} as const

/** A4 页边距。八份单据此前有 36 与 40 两种,统一到 40 —— 装订边更宽一点。 */
export const PAGE = {
    horizontal: 40,
    top: 36,
    /** 页脚是 position:absolute 的,正文底部要给它让出位置,否则会压在一起。 */
    bottom: 64,
} as const

/**
 * ★ 金额格式 —— 【三份文档各写了一遍,现在只有一份】★
 * 【它不是版式,是单据说了什么】所以 R3 盯着它:千分位、两位小数、en-US ——
 * 与此前三份 money() 和发票的 num() 【逐字同义】。本刀不改任何一个数字的样子,
 * 只是让它们不再有四份实现。
 */
export const money = (n: number, dp = 2) =>
    new Intl.NumberFormat('en-US', { minimumFractionDigits: dp, maximumFractionDigits: dp }).format(n)
