// app/components/pdf/noSignature.ts
// CONV-0 ②f:「本单据由系统生成,无需签章」——【一份措辞,八份单据】。
//
// ════════════════════════════════════════════════════════════════════════════
// ★ 这个文件存在的理由:两种语言政策共用同一批句子 ★
// ════════════════════════════════════════════════════════════════════════════
// 八份对外单据【不是同一种语言政策】,而这一点是本刀量出来的,不是假定的:
//
//   · 六份是【一律英文】——发票 / 采购单 / 销售订单 / 报价单 / 送货单 / 贷项凭证。
//     每一份的抬头都写着这条既定决策(「正文一律英文,收件人不是这套系统的用户」),
//     而它们的路由【一次 getTranslations 都不调】。界面切成中文,开出来的仍是英文。
//   · 两份【跟随界面语言】—— 客户对账单(它的正文键走 statements.doc.*)与
//     可追溯报告(RPT-1 的报表政策:它给打开系统的这个人看)。
//
// 所以中文那一句【实际会被印出来的只有这两份】。Tim 已知悉并裁定照此办理:
// 两种语言都写进 messages,六份印英文那一句。
//
// ★【为什么不让那六份各自硬写一句英文】★ 那会造出同一句话的第二份来源 ——
// 一份在 messages、一份在文档里,而两份必然漂开。这里改成:句子只有一处,
// 那六份【显式地取英文那一份】。于是"这份单据一律英文"从一条注释变成了
// 代码里看得见的一次选择。
import { MESSAGES } from '@/lib/i18n/config'

/** 八份对外单据各自的那一句。键就是单据族。 */
export type OutwardDocKind = keyof (typeof MESSAGES)['en']['pdf']['noSignature']

/**
 * 英文那一句 —— 给【一律英文】的那六份用。
 * 【刻意不叫 noSignature()】名字里带 En,是要让读的人在调用点就看见语言是被钉死的,
 * 而不是"忘了国际化"。
 */
export function noSignatureEn(kind: OutwardDocKind): string {
    return MESSAGES.en.pdf.noSignature[kind]
}
